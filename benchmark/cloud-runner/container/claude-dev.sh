# =============================================================================
# Claude Code Development Environment for Cloud Integration Tests
# =============================================================================
#
# This script builds and runs the Claude Code development container with
# proper credential mounts for AWS, GCP, and Azure.
#
# Usage:
#   ./claude-dev.sh              # Start Claude Code with --dangerously-skip-permissions
#   ./claude-dev.sh shell        # Start a bash shell instead
#   ./claude-dev.sh build        # Force rebuild the container
#   ./claude-dev.sh check        # Verify credential mounts work
#
# SSH keys are expected in output/ssh/ (generated by infra setup, not ~/.ssh)
#
# =============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../../.." && pwd)"

# Container configuration
IMAGE_NAME="claude-cloud-dev"
IMAGE_TAG="latest"
FULL_IMAGE="$IMAGE_NAME:$IMAGE_TAG"

# Output directory
OUTPUT_DIR="${OUTPUT_DIR:-$SCRIPT_DIR/output}"

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m'

log_info()  { echo -e "${BLUE}[INFO]${NC} $*"; }
log_ok()    { echo -e "${GREEN}[OK]${NC} $*"; }
log_warn()  { echo -e "${YELLOW}[WARN]${NC} $*"; }
log_error() { echo -e "${RED}[ERROR]${NC} $*" >&2; }

# =============================================================================
# Container Build
# =============================================================================

build_container() {
    local force="${1:-false}"

    if docker image inspect "$FULL_IMAGE" &>/dev/null && [[ "$force" != "true" ]]; then
        log_info "Container image exists: $FULL_IMAGE"
        return 0
    fi

    log_info "Building container image: $FULL_IMAGE"
    docker build -t "$FULL_IMAGE" -f "$SCRIPT_DIR/Dockerfile.claude-dev" "$SCRIPT_DIR"
    log_ok "Container built successfully"
}

# =============================================================================
# Credential Detection
# =============================================================================

check_credentials() {
    local has_creds=false

    echo ""
    echo "=== Credential Check ==="
    echo ""

    # AWS
    if [[ -d "$HOME/.aws" && -f "$HOME/.aws/credentials" ]]; then
        log_ok "AWS: ~/.aws/credentials found"
        has_creds=true
    elif [[ -n "${AWS_ACCESS_KEY_ID:-}" ]]; then
        log_ok "AWS: Environment variables set"
        has_creds=true
    else
        log_warn "AWS: No credentials found"
    fi

    # GCP
    if [[ -d "$HOME/.config/gcloud" ]]; then
        if [[ -f "$HOME/.config/gcloud/application_default_credentials.json" ]]; then
            log_ok "GCP: Application default credentials found"
            has_creds=true
        elif [[ -d "$HOME/.config/gcloud/legacy_credentials" ]]; then
            log_ok "GCP: Legacy credentials found"
            has_creds=true
        else
            log_warn "GCP: Config dir exists but no credentials"
        fi
    else
        log_warn "GCP: No credentials found"
    fi

    # Azure
    if [[ -d "$HOME/.azure" && -f "$HOME/.azure/azureProfile.json" ]]; then
        log_ok "Azure: ~/.azure found"
        has_creds=true
    else
        log_warn "Azure: No credentials found"
    fi

    # SSH (from output directory, not ~/.ssh)
    if [[ -f "$OUTPUT_DIR/ssh/iceberg-benchmark.pem" ]]; then
        log_ok "SSH: Key found at output/ssh/iceberg-benchmark.pem"
    else
        log_warn "SSH: No key found (run 'setup' to generate)"
    fi

    # Claude Code authentication (OAuth config or API key)
    if [[ -d "$HOME/.claude" && -f "$HOME/.claude/.credentials.json" ]]; then
        log_ok "Claude Code: OAuth credentials found (~/.claude)"
    elif [[ -n "${ANTHROPIC_API_KEY:-}" ]]; then
        log_ok "Claude Code: API key set"
    else
        log_error "Claude Code: No authentication found"
        echo ""
        echo "Either:"
        echo "  1. Run 'claude' on host first to set up OAuth login"
        echo "  2. Set ANTHROPIC_API_KEY='your-key-here'"
        return 1
    fi

    echo ""
    return 0
}

# =============================================================================
# Run Container
# =============================================================================

run_container() {
    local cmd="${1:-claude}"
    shift || true

    mkdir -p "$OUTPUT_DIR/ssh"

    # Build docker args
    local -a docker_args=("run" "-it" "--rm")

    # Claude Code OAuth config (from ~/.claude)
    if [[ -d "$HOME/.claude" ]]; then
        docker_args+=("-v" "$HOME/.claude:/home/claude/.claude")
    fi

    # Credential mounts (read-only where possible)
    # AWS - can be read-only
    if [[ -d "$HOME/.aws" ]]; then
        docker_args+=("-v" "$HOME/.aws:/credentials/aws:ro")
    fi

    # GCP - needs writable copy, entrypoint handles this
    if [[ -d "$HOME/.config/gcloud" ]]; then
        docker_args+=("-v" "$HOME/.config/gcloud:/credentials/gcloud:ro")
    fi

    # Azure - needs writable copy, entrypoint handles this
    if [[ -d "$HOME/.azure" ]]; then
        docker_args+=("-v" "$HOME/.azure:/credentials/azure:ro")
    fi

    # Git config (for commits from inside container)
    if [[ -f "$HOME/.gitconfig" ]]; then
        docker_args+=("-v" "$HOME/.gitconfig:/home/claude/.gitconfig:ro")
    fi

    # Output directory (read-write, contains SSH keys from infra setup)
    docker_args+=("-v" "$OUTPUT_DIR:/output")

    # Workspace (iceberg repo)
    docker_args+=("-v" "$PROJECT_ROOT:/workspace")

    # Environment variables
    docker_args+=("-e" "ANTHROPIC_API_KEY=${ANTHROPIC_API_KEY:-}")
    docker_args+=("-e" "TERM=${TERM:-xterm-256color}")
    docker_args+=("-e" "USER=claude")
    docker_args+=("-e" "HOME=/home/claude")

    # Pass through cloud environment variables if set
    [[ -n "${AWS_ACCESS_KEY_ID:-}" ]] && docker_args+=("-e" "AWS_ACCESS_KEY_ID")
    [[ -n "${AWS_SECRET_ACCESS_KEY:-}" ]] && docker_args+=("-e" "AWS_SECRET_ACCESS_KEY")
    [[ -n "${AWS_SESSION_TOKEN:-}" ]] && docker_args+=("-e" "AWS_SESSION_TOKEN")
    [[ -n "${AWS_REGION:-}" ]] && docker_args+=("-e" "AWS_REGION")
    [[ -n "${GOOGLE_APPLICATION_CREDENTIALS:-}" ]] && docker_args+=("-e" "GOOGLE_APPLICATION_CREDENTIALS")
    [[ -n "${CLOUDSDK_CORE_PROJECT:-}" ]] && docker_args+=("-e" "CLOUDSDK_CORE_PROJECT")
    [[ -n "${AZURE_SUBSCRIPTION_ID:-}" ]] && docker_args+=("-e" "AZURE_SUBSCRIPTION_ID")

    # Debug mode
    [[ -n "${DEBUG:-}" ]] && docker_args+=("-e" "DEBUG=1")

    # Image
    docker_args+=("$FULL_IMAGE")

    # Command
    case "$cmd" in
        shell|bash)
            docker_args+=("bash")
            ;;
        claude)
            docker_args+=("claude" "--dangerously-skip-permissions")
            [[ $# -gt 0 ]] && docker_args+=("$@")
            ;;
        *)
            docker_args+=("$cmd")
            [[ $# -gt 0 ]] && docker_args+=("$@")
            ;;
    esac

    docker "${docker_args[@]}"
}

# =============================================================================
# Usage
# =============================================================================

usage() {
    cat << EOF
Claude Code Development Environment for Cloud Integration Tests

USAGE:
    ./claude-dev.sh [command] [options...]

COMMANDS:
    (default)       Start Claude Code with --dangerously-skip-permissions
    shell           Start a bash shell in the container
    build           Force rebuild the container image
    check           Verify credentials and API key are configured

OPTIONS:
    Any additional options are passed to Claude Code.

ENVIRONMENT:
    ANTHROPIC_API_KEY    Optional if ~/.claude OAuth config exists.
    DEBUG=1              Enable verbose credential/mount debugging.

CREDENTIAL MOUNTS (auto-detected from host):
    ~/.claude            Claude Code OAuth config (mounted read-write)
    ~/.aws               AWS CLI credentials (mounted read-only)
    ~/.config/gcloud     GCP SDK credentials (copied to writable location)
    ~/.azure             Azure CLI credentials (copied to writable location)

SSH KEYS:
    SSH keys are NOT mounted from ~/.ssh. Instead, they are generated by
    the infrastructure setup script and stored in output/ssh/.
    Run './run.sh setup' first to create cloud resources and SSH keys.

EXAMPLES:
    # First time setup
    export ANTHROPIC_API_KEY='sk-ant-...'
    ./claude-dev.sh build
    ./claude-dev.sh check

    # Start Claude Code for development
    ./claude-dev.sh

    # Debug shell access
    DEBUG=1 ./claude-dev.sh shell

    # Pass options to Claude
    ./claude-dev.sh claude --model opus

EOF
}

# =============================================================================
# Main
# =============================================================================

main() {
    local cmd="${1:-}"

    case "$cmd" in
        build)
            build_container "true"
            ;;
        check)
            check_credentials
            ;;
        shell|bash)
            build_container
            run_container "shell"
            ;;
        help|--help|-h)
            usage
            ;;
        ""|claude)
            shift || true
            build_container
            if ! check_credentials; then
                exit 1
            fi
            echo ""
            log_info "Starting Claude Code..."
            echo ""
            run_container "claude" "$@"
            ;;
        *)
            build_container
            run_container "$@"
            ;;
    esac
}

main "$@"
